# Lead-time closed forms of SEISMIC §2.1 (params::derive::lead_time; V_p, V_s from the
# P+S synthesis; ONSITE_DECISION_S = 1.2; NETWORK_ALERT_S = 8). Checked against the
# section's own table before drawing: a mismatch skips the figure with a warning.
V_P_KMPS, V_S_KMPS, T_ONSITE_S, T_NETWORK_S = 6.0, 3.5, 1.2, 8.0


def _lead(r_km: float) -> tuple[float, float, float]:
    sp = r_km * (1 / V_S_KMPS - 1 / V_P_KMPS)
    return sp, sp - T_ONSITE_S, r_km / V_S_KMPS - T_NETWORK_S


