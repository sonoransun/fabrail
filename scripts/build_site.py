#!/usr/bin/env python3
"""Render the fabrail documents into the site's reading room, ``docs/read/*.html``.

Plan §3b: the ``read/`` pages are NARRATIVE, SPECIFICATION, TECHNICAL_DESIGN, PHYSICS,
SAFETY, SEISMIC, EXOTIC, FRONTIER, EXAMPLES, the capability matrix and the references
(plus SPECIFICATION_EXAMPLES and the generated PARAMETERS), rendered from ``docs/*.md``
by this script. ``tests/test_site.py::test_read_pages_current`` runs ``--check`` and
requires exit 0 (FAB-SW-013); the link and no-external-URL checks of FAB-SW-012 cover
the pages it writes. Owner: W5.

Usage, from the repo root::

    python scripts/build_site.py            # (re)write docs/read/*.html
    python scripts/build_site.py --check    # write nothing; exit 1 if docs/read/ is stale
    python scripts/build_site.py --strict   # also fail on warnings (dead links, unknown IDs)

Properties:

* Standard library only.
* Deterministic: no timestamps, no absolute paths, no file-system ordering. The same
  inputs give byte-identical pages; ``--check`` compares bytes.
* Offline: pages load only ``../assets/...`` files. A scheme-bearing URL in the Markdown
  (the documents use none) is shown as a scheme-less locator in ``<code>``, never as a
  link, so no page names another origin.
* A missing input (EXAMPLES.md until the Wave-3 examples pass) is skipped with a note,
  and links to it render as plain text until it exists.

The Markdown dialect is the GitHub-flavoured subset the documents use: ATX headings,
paragraphs, ``**strong**``, ``*em*``, ``_em_``, ``~~del~~``, code spans, fenced code
(backticks or tildes), block quotes, nested ordered and bullet lists (tight or loose),
pipe tables with alignment, thematic breaks, links, backslash escapes and hard breaks.
Math stays Unicode text. Differences from GitHub, on purpose:

* a pipe inside a backtick code span does not split a table cell, and ``\\|`` inside a
  code span keeps its backslash (the row regex of SPECIFICATION §0.3 is shown as the
  regex it is);
* HTML comments are dropped; any other raw HTML is shown as text, never passed through.

fabrail additions:

* heading ids are GitHub-style slugs, so ``FILE.md#slug`` fragments keep working, and a
  heading that starts with a section mark shows it as a number tag;
* requirement tables (the seven columns of SPECIFICATION §0.3 in SPECIFICATION,
  SPECIFICATION_EXAMPLES, EXOTIC and FRONTIER) give every row an anchor named by its ID
  and render the St. column as a status pill; every ``FAB-<AREA>-NNN`` elsewhere (outside
  code and headings) links to its row;
* ``[R#]`` links to that entry of references.html, whose entries carry the anchors;
* "DOC §n" (DOC one of the document names, with or without ``.md``), chains such as
  "§2, §26" and a bare "(§n)" inside a document link to the section heading, only
  when that heading exists; a link such as ``[SPECIFICATION.md §0](SPECIFICATION.md)``
  gains the section fragment;
* a few hand-authored inline SVG diagrams (``DIAGRAMS``) sit next to the text diagrams
  they summarise; the text block stays on the page as the "text version";
* banners: FRONTIER carries the frontier banner, EXOTIC the research-tier banner, and a
  frontier section of another document a frontier banner under its heading.
"""

