# --------------------------------------------------------------------------- block renderer


class Renderer:
    def __init__(self, site: Site, page: Page) -> None:
        self.site, self.page = site, page
        self.inline = Inline(site, page)
        self.emitted_rows: set[str] = set()
        self.placed: set[str] = set()

    # blocks ------------------------------------------------------------------------
    def blocks(self, nodes: list[Node], *, tight: bool = False) -> str:
        return "\n".join(self.block(n, tight=tight) for n in nodes)

    def block(self, node: Node, *, tight: bool = False) -> str:
        k = node.kind
        if k == "p":
            return self.paragraph(node, tight=tight)
        if k == "h":
            return self.heading(node)
        if k == "code":
            return self.code(node)
        if k == "table":
            return self.table(node)
        if k == "quote":
            inner = self.blocks(node.children)
            first = node.children[0] if node.children else None
            cls = ' class="note-status"' if first and first.kind == "p" and first.text.startswith("**Status") else ""
            return f"<blockquote{cls}>\n{inner}\n</blockquote>"
        if k == "list":
            return self.list(node)
        if k == "hr":
            return "<hr>"
        raise ValueError(k)

    def paragraph(self, node: Node, *, tight: bool = False) -> str:
        body = self.inline(node.text)
        if tight:
            return body
        m = re.match(r"^\*\*\[(R\d+)\]\*\*", node.text) if self.page.stem == "references" else None
        if m and m.group(1) in self.page.ref_defs:
            return f'<p id="{m.group(1)}" class="ref-entry">{body}</p>'
        return f"<p>{body}</p>"

    def heading_inner(self, node: Node) -> str:
        m = _SEC_HEAD.match(node.text)
        if m and node.text.startswith("§"):
            rest = node.text[m.end() :].lstrip()
            return f'<span class="sec-no">§{_text(m.group(1))}</span> {self.inline(rest, autolink=False)}'
        return self.inline(node.text, autolink=False)

    def heading(self, node: Node) -> str:
        lv = node.level
        anchor = f'<a class="h-anchor" href="#{node.hid}" aria-label="Link to this section">#</a>'
        return f'<h{lv} id="{node.hid}">{self.heading_inner(node)}{anchor}</h{lv}>'

    def code(self, node: Node) -> str:
        lang = f' data-lang="{_esc(node.lang)}"' if node.lang else ""
        return f"<pre{lang}><code>{_text(node.text)}</code></pre>"

    def list(self, node: Node) -> str:
        tag = "ol" if node.ordered else "ul"
        start = f' start="{node.start}"' if node.ordered and node.start != 1 else ""
        items = []
        for item in node.children:
            if not item:
                items.append("<li></li>")
                continue
            if node.loose:
                items.append(f"<li>{self.blocks(item)}</li>")
            else:
                items.append(f"<li>{self.blocks(item, tight=True)}</li>")
        return f"<{tag}{start}>\n" + "\n".join(items) + f"\n</{tag}>"

    def table(self, node: Node) -> str:
        is_req = self.page.stem in SPEC_DOCS and tuple(plain(h) for h in node.header) == REQ_HEADER
        ncols = len(node.header)

        def align(j: int) -> str:
            a = node.aligns[j] if j < len(node.aligns) else ""
            return f' class="ta-{a}"' if a else ""

        head = "".join(f"<th scope=\"col\"{align(j)}>{self.inline(h, autolink=False)}</th>" for j, h in enumerate(node.header))
        rows = []
        for r in node.rows:
            if len(r) != ncols:
                self.site.warn(f"{self.page.src.name}: table row with {len(r)} cells under a {ncols}-column header")
            cells = list(r) + [""] * (ncols - len(r))
            tr_id = ""
            tds = []
            for j, c in enumerate(cells):
                if j == 0 and self.page.fab_defs and re.fullmatch(r"FAB-[A-Z]{2,3}-\d{3}", c.strip()):
                    fid = c.strip()
                    if fid in self.page.fab_defs and fid not in self.emitted_rows:
                        self.emitted_rows.add(fid)
                        tr_id = f' id="{fid}"'
                        tds.append(f'<td><a class="req-id" href="#{fid}">{fid}</a></td>')
                        continue
                if is_req and j == 6 and c.strip() in STATUS:
                    cls, title = STATUS[c.strip()]
                    if self.page.stem == "FRONTIER":
                        title += " (of the model code; the badge is \N{TELESCOPE} when the maturity is frontier)"
                    tds.append(f'<td{align(j)}><span class="badge status {cls}" title="{_esc(title)}">{_text(c.strip())}</span></td>')
                    continue
                tds.append(f"<td{align(j)}>{_break_code(self.inline(c))}</td>")
            rows.append(f"<tr{tr_id}>" + "".join(tds) + "</tr>")
        cls = ' class="req-table"' if is_req else ""
        return (
            f'<div class="table-wrap" role="region" aria-label="Scrollable table" tabindex="0">'
            f"<table{cls}>\n<thead><tr>{head}</tr></thead>\n<tbody>\n" + "\n".join(rows) + "\n</tbody>\n</table></div>"
        )

    # diagrams -----------------------------------------------------------------------
    def figure(self, dg: Diagram, node: Node) -> str | None:
        svg = dg.build(dg.fid, node)  # type: ignore[operator]
        if svg is None:
            self.site.warn(f"{self.page.src.name}: diagram {dg.fid} skipped (its source block changed; "
                           "update DIAGRAMS in scripts/build_site.py)")
            return None
        self.placed.add(dg.fid)
        self.page.ids.add(dg.fid)
        return (
            f'<figure class="diagram" id="{dg.fid}">\n<div class="diagram-scroll">\n{svg}\n</div>\n'
            f"<figcaption>{self.inline(dg.caption)}</figcaption>\n</figure>"
        )

    # page body ------------------------------------------------------------------------
    def body(self) -> tuple[Node | None, str, list[tuple[int, str, str]]]:
        """(the h1 node, body HTML without the h1, TOC entries (level, id, inner HTML))."""
        h1: Node | None = None
        parts: list[str] = []
        toc: list[tuple[int, str, str]] = []
        section = ""
        counts = {"code": 0, "table": 0}
        mine = [d for d in DIAGRAMS if d.stem == self.page.stem]
        for node in self.page.blocks:
            if node.kind == "h" and node.level == 1 and h1 is None:
                h1 = node
                continue
            if node.kind == "h":
                if node.label:
                    section, counts = node.label, {"code": 0, "table": 0}
                parts.append(self.heading(node))
                if node.level in (2, 3):
                    inner = re.sub(r"</?a\b[^>]*>", "", self.heading_inner(node))
                    toc.append((node.level, node.hid, inner))
                if node.level == 2 and self.page.stem != "FRONTIER":
                    t = plain(node.text)
                    if "\N{TELESCOPE}" in t or re.match(r"^(?:\d+\s+)?Frontier tier\b", t):
                        title, text = SECTION_FRONTIER_BANNER
                        parts.append(f'<div class="banner frontier" role="note"><span class="banner-title">'
                                     f"{_text(title)}</span> {self.inline(text)}</div>")
                continue
            if node.kind in counts:
                idx = counts[node.kind]
                counts[node.kind] += 1
                hit = next((d for d in mine if d.section == section and d.kind == node.kind and d.index == idx), None)
                if hit and node.kind == "code":
                    fig = self.figure(hit, node)
                    if fig:
                        parts.append(fig)
                        parts.append('<details class="text-version">\n<summary>Text version</summary>\n'
                                     + self.code(node) + "\n</details>")
                        continue
                parts.append(self.block(node))
                if hit and node.kind == "table":
                    fig = self.figure(hit, node)
                    if fig:
                        parts.append(fig)
                continue
            parts.append(self.block(node))
        for d in mine:
            if d.fid not in self.placed:
                self.site.warn(f"{self.page.src.name}: diagram {d.fid} not placed (no {d.kind} #{d.index} "
                               f"under §{d.section})")
        return h1, "\n".join(parts), toc


