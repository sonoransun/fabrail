def _break_code(frag: str) -> str:
    """Offer line breaks inside long code spans of a table cell (after ::, /, _ and .)."""

    def one(m: re.Match) -> str:
        body = m.group(1)
        return "<code>" + (_WBR.sub(r"\1<wbr>", body) if len(body) > 20 else body) + "</code>"

    return re.sub(r"<code>(.*?)</code>", one, frag)


