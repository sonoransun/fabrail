def build(site: Site) -> dict[str, str]:
    """Output name -> page text, for every page this run produces."""
    out: dict[str, str] = {}
    for doc in DOC_LIST:
        page = site.pages.get(doc.stem)
        if page is not None:
            out[f"{doc.stem}.html"] = render_doc(site, page)
    out["index.html"] = render_index(site)
    _verify_fragments(site, out)
    return out


def _verify_fragments(site: Site, pages: dict[str, str]) -> None:
    """Warn about any link into a read/ page whose fragment names no id there."""
    ids = {name: set(re.findall(r'\bid="([^"]+)"', text)) for name, text in pages.items()}
    for name, text in pages.items():
        for target, frag in re.findall(r'\bhref="([^"#:]*)#([^"]+)"', text):
            tname = target or name
            if tname in ids and frag not in ids[tname]:
                site.warn(f"read/{name}: link to {tname}#{frag}, which has no such id")


def _generated_files() -> list[Path]:
    if not OUT_DIR.is_dir():
        return []
    files = []
    for p in sorted(OUT_DIR.glob("*.html")):
        try:
            head = p.read_text(encoding="utf-8")[:2048]
        except (OSError, UnicodeDecodeError):
            continue
        if MARKER in head:
            files.append(p)
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="write nothing; exit 1 if any docs/read/ page is missing, stale or orphaned")
    ap.add_argument("--strict", action="store_true",
                    help="also exit 1 on renderer warnings (unresolved links, unknown IDs, skipped diagrams)")
    ap.add_argument("-q", "--quiet", action="store_true", help="print only problems")
    args = ap.parse_args(argv)

    site = load_site()
    pages = {name: text.encode("utf-8") for name, text in build(site).items()}
    notes = [f"note: docs/{d.stem}.md not found; skipped (not written yet)" for d in site.missing]
    listed = {f"{d.stem}.md" for d in DOC_LIST}
    notes += [
        f"note: docs/{p.name} is not in DOC_LIST; not rendered"
        for p in sorted(DOCS.glob("*.md"))
        if p.name not in listed
    ]
    orphans = [p for p in _generated_files() if p.name not in pages]
    if not args.quiet:
        for n in notes:
            print(n)
    for w in site.warnings:
        print(f"warning: {w}", file=sys.stderr)
    failed_strict = args.strict and bool(site.warnings)

    if args.check:
        problems = []
        for name, data in pages.items():
            dest = OUT_DIR / name
            if not dest.is_file():
                problems.append(f"missing: docs/read/{name}")
            elif dest.read_bytes() != data:
                problems.append(f"stale: docs/read/{name}")
        problems += [f"orphan: docs/read/{p.name} (its source is gone)" for p in orphans]
        if problems:
            print(f"docs/read/ is not current; run: python {GENERATOR}")
            for p in problems:
                print("  " + p)
            return 1
        if not args.quiet:
            print(f"docs/read/ is current ({len(pages)} pages)")
        return 1 if failed_strict else 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    written = unchanged = 0
    for name, data in pages.items():
        dest = OUT_DIR / name
        if dest.is_file() and dest.read_bytes() == data:
            unchanged += 1
            continue
        dest.write_bytes(data)
        written += 1
    for p in orphans:
        p.unlink()
    if not args.quiet:
        print(f"docs/read/: {written} written, {unchanged} unchanged, {len(orphans)} removed "
              f"({len(site.pages)} documents, {len(site.fab)} requirement anchors, {len(site.refs)} sources)")
    return 1 if failed_strict else 0


if __name__ == "__main__":
    sys.exit(main())
