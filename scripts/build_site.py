def nav_pages() -> tuple[tuple[str, str], ...]:
    """(href, label) of the site pages, read from nav.js PAGES (the canonical list)."""
    try:
        js = NAV_JS.read_text(encoding="utf-8")
        body = js[js.index("var PAGES = [") :]
        body = body[: body.index("];")]
    except (OSError, ValueError):
        return NAV_FALLBACK
    pages = re.findall(r'key:\s*"([^"]+)",\s*href:\s*"([^"]+)",\s*label:\s*"([^"]+)"', body)
    return tuple((h, lab) for _, h, lab in pages) or NAV_FALLBACK


def _words(text: str) -> int:
    return len(re.findall(r"[^\W_]+(?:[-'’][^\W_]+)*", text))


def _count(n: int) -> str:
    return f"{n:,}"


