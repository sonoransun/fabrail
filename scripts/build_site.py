def _n(v: float) -> str:
    """Deterministic SVG number: integer when integral, else one decimal."""
    r = round(v, 1)
    return str(int(r)) if r == int(r) else f"{r:.1f}"


class Svg:
    """A tiny SVG builder for the hand-authored diagrams (themed through read.css)."""

    def __init__(self, fid: str, width: int, height: int, title: str, desc: str) -> None:
        self.fid, self.w, self.h = fid, width, height
        self.title, self.desc = title, desc
        self.parts: list[str] = []

    def rect(self, x: float, y: float, w: float, h: float, cls: str, rx: float = 6) -> None:
        self.parts.append(
            f'<rect x="{_n(x)}" y="{_n(y)}" width="{_n(w)}" height="{_n(h)}" rx="{_n(rx)}" class="{cls}"/>'
        )

    def text(self, x: float, y: float, s: str, cls: str = "dg-t", anchor: str = "start") -> None:
        a = "" if anchor == "start" else f' text-anchor="{anchor}"'
        self.parts.append(f'<text x="{_n(x)}" y="{_n(y)}" class="{cls}"{a}>{_text(s)}</text>')

    def path(self, pts: list[tuple[float, float]], cls: str = "dg-edge", end: bool = True, start: bool = False) -> None:
        d = "M" + " L".join(f"{_n(x)},{_n(y)}" for x, y in pts)
        mk = (f' marker-end="url(#{self.fid}-ah)"' if end else "") + (
            f' marker-start="url(#{self.fid}-ah)"' if start else ""
        )
        self.parts.append(f'<path d="{d}" class="{cls}"{mk}/>')

    def raw(self, frag: str) -> None:
        self.parts.append(frag)

    def node(self, cx: float, cy: float, w: float, h: float, name: str, sub: str = "", cls: str = "dg-node",
             tcls: str = "dg-t dg-mono dg-tb") -> None:
        self.rect(cx - w / 2, cy - h / 2, w, h, cls)
        if sub:
            self.text(cx, cy - 2, name, tcls, "middle")
            self.text(cx, cy + 12, sub, "dg-xs", "middle")
        else:
            self.text(cx, cy + 4, name, tcls, "middle")

    def render(self) -> str:
        f = self.fid
        head = (
            f'<svg class="dg" viewBox="0 0 {self.w} {self.h}" role="img" '
            f'aria-labelledby="{f}-title {f}-desc">\n'
            f'<title id="{f}-title">{_text(self.title)}</title>\n'
            f'<desc id="{f}-desc">{_text(self.desc)}</desc>\n'
            f'<defs><marker id="{f}-ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" '
            f'markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" class="dg-ah"/>'
            f"</marker></defs>\n"
        )
        return head + "\n".join(self.parts) + "\n</svg>"


