def side_nav(site: Site, current: str | None, toc: list[tuple[int, str, str]]) -> str:
    items = []
    for doc in DOC_LIST:
        if doc.stem not in site.pages:
            continue
        cur = ' aria-current="page"' if doc.stem == current else ""
        items.append(f'<li><a href="{doc.stem}.html"{cur}>{_text(doc.label)}</a></li>')
    out = [
        '<aside class="read-side" id="read-side" aria-label="Documents and contents">',
        '<nav class="side-docs" aria-label="Documents">',
        '<p class="side-title"><a href="index.html">Documents</a></p>',
        "<ul>", *items, "</ul>", "</nav>",
    ]
    if toc:
        out += ['<nav class="toc" aria-label="On this page">', '<p class="side-title">On this page</p>',
                toc_list(toc), "</nav>"]
    out.append("</aside>")
    return "\n".join(out)


def toc_list(toc: list[tuple[int, str, str]], *, max_level: int = 3) -> str:
    """Nested <ol> of h2 entries with their h3 children."""
    out = ["<ol>"]
    open_sub = False
    for level, hid, inner in toc:
        if level > max_level:
            continue
        if level == 2:
            if open_sub:
                out.append("</ol></li>")
                open_sub = False
            elif len(out) > 1:
                out.append("</li>")
            out.append(f'<li><a href="#{hid}">{inner}</a>')
        else:
            if not open_sub:
                if len(out) == 1:
                    out.append("<li>")
                out.append("<ol>")
                open_sub = True
            out.append(f'<li><a href="#{hid}">{inner}</a></li>')
    if open_sub:
        out.append("</ol></li>")
    elif len(out) > 1:
        out.append("</li>")
    out.append("</ol>")
    return "\n".join(out)


def render_doc(site: Site, page: Page) -> str:
    r = Renderer(site, page)
    h1, body, toc = r.body()
    doc = page.doc
    words = _words(page.text)
    meta = [f"<code>docs/{page.src.name}</code>", f"{_count(words)} words",
            f"about {max(1, round(words / 230))} min"]
    if page.fab_defs:
        meta.insert(1, f"{_count(len(page.fab_defs))} requirements")
    if page.ref_defs:
        meta.insert(1, f"{_count(len(page.ref_defs))} sources")
    h1_html = (
        f'<h1 id="{h1.hid}">{r.heading_inner(h1)}</h1>' if h1 is not None
        else f'<h1 id="read-title">{_text(doc.label)}</h1>'
    )
    head = [
        '<article class="prose">',
        '<header class="doc-head">',
        '<p class="eyebrow doc-meta">' + " · ".join(meta) + "</p>",
        h1_html,
        "</header>",
    ]
    if doc.stem in TOP_BANNERS:
        kind, title, text = TOP_BANNERS[doc.stem]
        head.append(f'<div class="banner {kind}" role="note"><span class="banner-title">{_text(title)}</span> '
                    f"{Inline(site, page)(text)}</div>")
    h2s = [t for t in toc if t[0] == 2]
    if len(h2s) >= 3:
        head.append('<details class="toc-inline" id="read-toc">\n<summary>Contents</summary>\n'
                    + toc_list(h2s, max_level=2) + "\n</details>")
    tail = [
        tier_legend(site),
        f'<p class="source-note">Rendered from <code>docs/{page.src.name}</code> by <code>{GENERATOR}</code>. '
        "The Markdown is the source; edit it and rerun the script.</p>",
        "</article>",
        pager(site, doc.stem),
    ]
    body_html = "\n".join(head + [body] + tail)
    return page_shell(
        title=f"{doc.label} · fabrail",
        description=doc.blurb,
        body_html=body_html,
        side_html=side_nav(site, doc.stem, toc),
        current=doc.stem,
    )


def pager(site: Site, stem: str) -> str:
    order = [d for d in DOC_LIST if d.stem in site.pages]
    k = next(i for i, d in enumerate(order) if d.stem == stem)
    links = []
    if k > 0:
        p = order[k - 1]
        links.append(f'<a class="pager-prev" href="{p.stem}.html"><span>Previous</span>{_text(p.label)}</a>')
    if k + 1 < len(order):
        q = order[k + 1]
        links.append(f'<a class="pager-next" href="{q.stem}.html"><span>Next</span>{_text(q.label)}</a>')
    return '<nav class="pager" aria-label="Previous and next document">\n' + "\n".join(links) + "\n</nav>"


def render_index(site: Site) -> str:
    groups = []
    for g in GROUPS:
        docs = [d for d in DOC_LIST if d.group == g]
        if not docs:
            continue
        gid = "g-" + gh_slug(g)
        cards = []
        for d in docs:
            page = site.pages.get(d.stem)
            if page is None:
                cards.append(
                    f'<li><div class="card card--missing"><h3>{_text(d.label)}</h3><p>{_text(d.blurb)}</p>'
                    f'<p class="card-meta"><code>docs/{d.stem}.md</code> is not written yet; this page appears '
                    "when it is.</p></div></li>"
                )
                continue
            meta = [f"<code>docs/{page.src.name}</code>"]
            if page.fab_defs:
                meta.append(f"{_count(len(page.fab_defs))} requirements")
            if page.ref_defs:
                meta.append(f"{_count(len(page.ref_defs))} sources")
            meta.append(f"{_count(_words(page.text))} words")
            cards.append(
                f'<li><a class="card" href="{d.stem}.html"><h3>{_text(d.label)}</h3>'
                f"<p>{Inline(site, page)(d.blurb, autolink=False)}</p>"
                f'<p class="card-meta">{" · ".join(meta)}</p></a></li>'
            )
        groups.append(
            f'<section class="doc-group" aria-labelledby="{gid}">\n<h2 id="{gid}">{_text(g)}</h2>\n'
            f'<ul class="doc-cards">\n' + "\n".join(cards) + "\n</ul>\n</section>"
        )
    n_req = len(site.fab)
    n_ref = len(site.refs)
    body = "\n".join([
        '<article class="prose read-index">',
        '<header class="doc-head">',
        '<p class="eyebrow">Reading room</p>',
        '<h1 id="read-title">Documents</h1>',
        f'<p class="lede">The repository\'s Markdown documents, rendered for reading: {_count(n_req)} requirement '
        f"rows, each with its own anchor, and {_count(n_ref)} numbered sources. The Markdown in "
        "<code>docs/</code> is the source; these pages are regenerated from it.</p>",
        "</header>",
        '<p class="callout scope">Everything here describes simulation and analysis in this repository. Nothing '
        "has run on hardware, and no document claims compliance or certification.</p>",
        *groups,
        tier_legend(site),
        f'<p class="source-note">Rendered by <code>{GENERATOR}</code>; <code>--check</code> reports stale pages.</p>',
        "</article>",
    ])
    return page_shell(
        title="Documents · fabrail",
        description="The fabrail documents rendered for reading: narrative, specification, design, physics, "
        "safety, seismic, tiers and references.",
        body_html=body,
        side_html=side_nav(site, None, []),
        current=None,
    )


