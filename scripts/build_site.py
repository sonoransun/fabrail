def plain(md: str) -> str:
    """Plain text of inline Markdown (slugs, titles, section labels)."""
    s = re.sub(r"<!--.*?-->", "", md, flags=re.S)
    s = re.sub(r"!?\[((?:[^\[\]]|\[[^\[\]]*\])*)\]\([^)]*\)", r"\1", s)
    s = re.sub(r"\\([!-/:-@\[-`{-~])", r"\1", s)
    s = s.replace("`", "")
    s = re.sub(r"\*\*|~~|(?<!\w)\*|\*(?!\w)", "", s)
    return " ".join(s.split())


def gh_slug(text: str) -> str:
    """GitHub-style heading slug: lower case, punctuation removed, spaces to hyphens."""
    s = re.sub(r"[^\w\- ]", "", text.strip().lower())
    return s.replace(" ", "-") or "section"


def scheme_less(url: str) -> str:
    return re.sub(r"^[a-z][a-z0-9+.-]*://", "", url, flags=re.I)


