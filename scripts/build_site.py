# --------------------------------------------------------------------------- blocks

_FENCE = re.compile(r"^( {0,3})(`{3,}|~{3,})(.*)$")
_ATX = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*$")
_HR = re.compile(r"^ {0,3}(?:(?:-[ \t]*){3,}|(?:\*[ \t]*){3,}|(?:_[ \t]*){3,})$")
_LIST = re.compile(r"^( {0,3})([-*+]|\d{1,9}[.)])(?:([ \t]+)(.*))?$")
_QUOTE = re.compile(r"^ {0,3}>")
_DELIM = re.compile(r"^ {0,3}\|?[ \t]*:?-+:?[ \t]*(?:\|[ \t]*:?-+:?[ \t]*)*\|?[ \t]*$")


@dataclass
class Node:
    kind: str  # h, p, code, table, quote, list, hr
    text: str = ""  # h/p: inline Markdown; code: the literal text
    level: int = 0  # h: 1..6
    lang: str = ""  # code: info-string word
    children: list = field(default_factory=list)  # quote: [Node]; list: [[Node], ...] per item
    header: list = field(default_factory=list)  # table
    aligns: list = field(default_factory=list)  # table: "l" | "c" | "r" | ""
    rows: list = field(default_factory=list)  # table
    ordered: bool = False  # list
    start: int = 1  # list
    loose: bool = False  # list
    hid: str = ""  # h: element id
    label: str = ""  # h: section label ("16.1", "X9"), if the heading starts with one


def _indent(line: str) -> int:
    return len(line) - len(line.lstrip(" "))


def _fence_open(line: str) -> tuple[int, str, str] | None:
    m = _FENCE.match(line)
    if not m:
        return None
    fence, info = m.group(2), m.group(3).strip()
    if fence[0] == "`" and "`" in info:
        return None
    return len(m.group(1)), fence, (info.split()[0] if info else "")


def _is_table_start(lines: list[str], i: int) -> bool:
    return (
        lines[i].lstrip(" ").startswith("|")
        and i + 1 < len(lines)
        and "-" in lines[i + 1]
        and bool(_DELIM.match(lines[i + 1]))
    )


def _interrupts_paragraph(lines: list[str], i: int) -> bool:
    """Whether line i starts a block that ends the paragraph before it."""
    line = lines[i]
    if not line.strip():
        return True
    s = line.lstrip(" ")
    if _indent(line) > 3:
        return False
    if s.startswith("<!--") or s.startswith(">") or _fence_open(line) or _ATX.match(line) or _HR.match(line):
        return True
    m = _LIST.match(line)
    if m and (m.group(4) or "").strip():
        marker = m.group(2)
        if marker[-1] not in ".)" or marker[:-1] == "1":
            return True
    return _is_table_start(lines, i)


def _find_run(s: str, start: int, k: int) -> int:
    """Index of the next run of exactly k backticks at or after start, or -1."""
    i = start
    while True:
        i = s.find("`" * k, i)
        if i < 0:
            return -1
        j = i + k
        if (i == 0 or s[i - 1] != "`") and (j >= len(s) or s[j] != "`"):
            return i
        while i < len(s) and s[i] == "`":
            i += 1


def split_row(line: str) -> list[str]:
    """Cells of a pipe-table row; pipes inside code spans or escaped as \\| do not split."""
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    cells: list[str] = []
    cur: list[str] = []
    i, n = 0, len(s)
    while i < n:
        c = s[i]
        if c == "\\" and i + 1 < n:
            cur.append(s[i : i + 2])
            i += 2
        elif c == "`":
            j = i
            while j < n and s[j] == "`":
                j += 1
            k = _find_run(s, j, j - i)
            if k < 0:
                cur.append(s[i:j])
                i = j
            else:
                cur.append(s[i : k + (j - i)])
                i = k + (j - i)
        elif c == "|":
            cells.append("".join(cur).strip())
            cur = []
            i += 1
        else:
            cur.append(c)
            i += 1
    cells.append("".join(cur).strip())
    return cells


def parse_blocks(lines: list[str]) -> list[Node]:
    out: list[Node] = []
    i, n = 0, len(lines)
    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        s = line.lstrip(" ")
        ind = _indent(line)

        # indented code (not used by the documents, supported for safety)
        if ind >= 4:
            buf = []
            while i < n and (not lines[i].strip() or _indent(lines[i]) >= 4):
                buf.append(lines[i][4:] if lines[i].strip() else "")
                i += 1
            while buf and not buf[-1]:
                buf.pop()
            out.append(Node("code", text="\n".join(buf)))
            continue

        # HTML comment block: dropped
        if s.startswith("<!--"):
            j = i
            rest = s[4:]
            while "-->" not in rest:
                j += 1
                if j >= n:
                    break
                rest = lines[j]
            i = j + 1
            continue

        fo = _fence_open(line)
        if fo:
            f_ind, fence, lang = fo
            buf = []
            i += 1
            while i < n:
                cl = lines[i]
                cm = re.match(r"^ {0,3}(" + re.escape(fence[0]) + "{" + str(len(fence)) + r",})[ \t]*$", cl)
                if cm:
                    i += 1
                    break
                buf.append(cl[min(f_ind, _indent(cl)) :])
                i += 1
            out.append(Node("code", text="\n".join(buf), lang=lang))
            continue

        m = _ATX.match(line)
        if m:
            out.append(Node("h", text=(m.group(2) or "").strip(), level=len(m.group(1))))
            i += 1
            continue

        if _HR.match(line):
            out.append(Node("hr"))
            i += 1
            continue

        if _is_table_start(lines, i):
            header = split_row(lines[i])
            aligns = []
            for c in split_row(lines[i + 1]):
                c = c.strip()
                left, right = c.startswith(":"), c.endswith(":")
                aligns.append("c" if left and right else "r" if right else "l" if left else "")
            rows = []
            i += 2
            while i < n and lines[i].strip() and lines[i].lstrip(" ").startswith("|"):
                rows.append(split_row(lines[i]))
                i += 1
            out.append(Node("table", header=header, aligns=aligns, rows=rows))
            continue

        if _QUOTE.match(line):
            buf = []
            while i < n:
                cl = lines[i]
                if _QUOTE.match(cl):
                    t = cl.lstrip(" ")[1:]
                    buf.append(t[1:] if t.startswith(" ") else t)
                    i += 1
                elif cl.strip() and buf and buf[-1].strip() and not _interrupts_paragraph(lines, i):
                    buf.append(cl)  # lazy continuation
                    i += 1
                else:
                    break
            out.append(Node("quote", children=parse_blocks(buf)))
            continue

        if _LIST.match(line):
            node, i = _parse_list(lines, i)
            out.append(node)
            continue

        # paragraph
        buf = [s]
        i += 1
        while i < n and not _interrupts_paragraph(lines, i):
            buf.append(lines[i].strip() if not lines[i].endswith("  ") else lines[i].lstrip())
            i += 1
        out.append(Node("p", text="\n".join(buf)))
    return out


def _list_kind(marker: str) -> tuple[bool, str]:
    ordered = marker[-1] in ".)"
    return ordered, (marker[-1] if ordered else marker)


def _parse_list(lines: list[str], i: int) -> tuple[Node, int]:
    n = len(lines)
    m = _LIST.match(lines[i])
    assert m
    ordered, kind = _list_kind(m.group(2))
    start = int(m.group(2)[:-1]) if ordered else 1
    items: list[list[Node]] = []
    loose = False
    blank_before = False
    while i < n:
        if _HR.match(lines[i]):
            break
        m = _LIST.match(lines[i])
        if not m or _list_kind(m.group(2)) != (ordered, kind):
            break
        if items and blank_before:
            loose = True
        marker_w = len(m.group(1)) + len(m.group(2))
        pad, text = m.group(3) or "", m.group(4) or ""
        if not text.strip():
            content = marker_w + 1
            first = ""
        elif len(pad.expandtabs(4)) > 4:
            content = marker_w + 1
            first = pad[1:] + text
        else:
            content = marker_w + len(pad)
            first = text
        item = [first]
        in_fence = bool(_fence_open(first))
        i += 1
        blank_before = False
        internal_blank = False
        while i < n:
            cl = lines[i]
            if not cl.strip():
                j = i
                while j < n and not lines[j].strip():
                    j += 1
                if j < n and _indent(lines[j]) >= content:
                    item.extend([""] * (j - i))
                    internal_blank = True
                    i = j
                    continue
                i = j
                blank_before = True
                break
            if _indent(cl) >= content:
                item.append(cl[content:])
                if _fence_open(cl[content:]) or (in_fence and re.match(r"^ {0,3}(`{3,}|~{3,})\s*$", cl[content:])):
                    in_fence = not in_fence
                i += 1
                continue
            if _LIST.match(cl) and (_LIST.match(cl).group(4) or "").strip():
                break  # a list marker left of the content column: next item or another list
            if not in_fence and item[-1].strip() and not _interrupts_paragraph(lines, i):
                item.append(cl.strip())  # lazy paragraph continuation
                i += 1
                continue
            break
        children = parse_blocks(item)
        if internal_blank and len(children) > 1:
            loose = True
        items.append(children)
        if blank_before and not (i < n and _LIST.match(lines[i]) and _indent(lines[i]) < content):
            break
    return Node("list", ordered=ordered, start=start, loose=loose, children=items), i


