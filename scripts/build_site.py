class Inline:
    """Inline Markdown to HTML for one page. Placeholders (\\x00n\\x00) protect finished HTML."""

    def __init__(self, site: Site, page: Page) -> None:
        self.site = site
        self.page = page
        self.slots: list[str] = []
        self.link_doc: dict[int, str] = {}

    def __call__(self, md: str, *, autolink: bool = True) -> str:
        s = self._tokenize(md)
        s = self._links(s)
        s = self._fmt(s, autolink=autolink)
        return self._restore(s)

    def _stash(self, frag: str) -> str:
        self.slots.append(frag)
        return f"\x00{len(self.slots) - 1}\x00"

    def _restore(self, s: str) -> str:
        for _ in range(32):
            if "\x00" not in s:
                break
            s = re.sub(r"\x00(\d+)\x00", lambda m: self.slots[int(m.group(1))], s)
        return s

    def _tokenize(self, s: str) -> str:
        out: list[str] = []
        i, n = 0, len(s)
        while i < n:
            c = s[i]
            if c == "\\" and i + 1 < n:
                if s[i + 1] in _ASCII_PUNCT:
                    out.append(self._stash(_text(s[i + 1])))
                    i += 2
                    continue
                if s[i + 1] == "\n":
                    out.append(self._stash("<br>\n"))
                    i += 2
                    continue
            if c == "`":
                j = i
                while j < n and s[j] == "`":
                    j += 1
                k = _find_run(s, j, j - i)
                if k < 0:
                    out.append(s[i:j])
                    i = j
                    continue
                code = s[j:k].replace("\n", " ")
                if len(code) >= 2 and code[0] == " " and code[-1] == " " and code.strip():
                    code = code[1:-1]
                out.append(self._stash(f"<code>{_text(code)}</code>"))
                i = k + (j - i)
                continue
            if s.startswith("<!--", i):
                e = s.find("-->", i + 4)
                if e >= 0:
                    i = e + 3
                    continue
            if c == " ":
                m = re.match(r" {2,}\n", s[i:])
                if m:
                    out.append(self._stash("<br>\n"))
                    i += m.end()
                    continue
            out.append(c)
            i += 1
        return "".join(out)

    def _links(self, s: str) -> str:
        def repl(m: re.Match) -> str:
            bang, label, url = m.group(1), m.group(2), m.group(3).strip()
            inner = self._fmt(label, autolink=False)
            if bang:
                href, _ = self.site_href(url, label)
                if href is None:
                    return self._stash(f'<span class="img-missing">{inner}</span>')
                return self._stash(f'<img src="{_esc(href)}" alt="{_esc(plain(label))}" loading="lazy">')
            if re.match(r"^[a-z][a-z0-9+.-]*://", url, re.I):
                self.site.warn(f"{self.page.src.name}: external link {url!r} shown as a locator")
                loc = f'<code class="locator">{_text(scheme_less(url))}</code>'
                return self._stash(f"{inner} ({loc})")
            href, doc = self.site_href(url, label)
            if href is None:
                return self._stash(f'<span class="dead-link">{inner}</span>')
            key = self._stash(f'<a href="{_esc(href)}">{inner}</a>')
            if doc:
                self.link_doc[int(key.strip("\x00"))] = doc
            return key

        return _LINK.sub(repl, s)

    def site_href(self, url: str, label: str) -> tuple[str | None, str | None]:
        """(href from docs/read/, target document stem) for a link written in docs/<x>.md."""
        page, site = self.page, self.site
        if url.startswith("#"):
            frag = url[1:]
            if frag not in page.ids:
                site.warn(f"{page.src.name}: fragment #{frag} has no heading; link kept without it")
            return url, page.stem
        path, _, frag = url.partition("#")
        path = path.split("?", 1)[0]
        if re.match(r"^(?:mailto|tel):", path, re.I):
            return None, None
        target = (DOCS / path).resolve()
        try:
            rel = target.relative_to(DOCS.resolve()).as_posix()
        except ValueError:
            site.warn(f"{page.src.name}: link {url!r} leaves docs/; shown as text")
            return None, None
        if rel.endswith(".md") and "/" not in rel:
            stem = rel[:-3]
            tp = site.pages.get(stem)
            if tp is None:
                site.warn(f"{page.src.name}: link to {rel}, which is not rendered; shown as text")
                return None, None
            if frag and frag not in tp.ids:
                site.warn(f"{page.src.name}: {rel}#{frag} has no such heading; fragment dropped")
                frag = ""
            if not frag:
                m = _SEC.search(plain(label))
                if m and m.group(1) in tp.sections:
                    frag = tp.sections[m.group(1)]
            base = "" if stem == page.stem else tp.href
            return (base + (f"#{frag}" if frag else "")) or "#", stem
        if target.is_file() or target.is_dir():
            return "../" + rel + (f"#{frag}" if frag else ""), None
        site.warn(f"{page.src.name}: link target docs/{rel} does not exist; shown as text")
        return None, None

    def _bare_url(self, m: re.Match) -> str:
        url = m.group(0).rstrip(".,;:")
        tail = m.group(0)[len(url) :]
        self.site.warn(f"{self.page.src.name}: bare URL {url!r} shown as a locator")
        return self._stash(f'<code class="locator">{_text(scheme_less(url))}</code>') + tail

    def _fmt(self, s: str, *, autolink: bool) -> str:
        s = _URL.sub(self._bare_url, s)
        s = _text(s)
        s = _DEL.sub(r"<del>\1</del>", s)
        s = _STRONG.sub(r"<strong>\1</strong>", s)
        s = _STRONG_U.sub(r"<strong>\1</strong>", s)
        s = _EM.sub(r"<em>\1</em>", s)
        s = _EM_U.sub(r"<em>\1</em>", s)
        if autolink:
            s = self._sections(s)
            s = _DOCFILE.sub(self._docfile, s)
            s = _FAB.sub(self._fab, s)
            s = _REF.sub(self._ref, s)
        return s

    def _docfile(self, m: re.Match) -> str:
        stem = m.group(1)
        tp = self.site.pages.get(stem)
        if tp is None or stem == self.page.stem:
            return m.group(0)
        return self._stash(f'<a class="doc-link" href="{tp.href}">{m.group(0)}</a>')

    def _fab(self, m: re.Match) -> str:
        fid = m.group(1)
        stem = self.site.fab.get(fid)
        if stem is None:
            self.site.warn(f"{self.page.src.name}: {fid} is not defined in a requirement table; not linked")
            return fid
        href = f"#{fid}" if stem == self.page.stem else f"{stem}.html#{fid}"
        return self._stash(f'<a class="req-link" href="{href}">{fid}</a>')

    def _ref(self, m: re.Match) -> str:
        rid = f"R{m.group(1)}"
        if rid not in self.site.refs:
            if "references" in self.site.pages:
                self.site.warn(f"{self.page.src.name}: [{rid}] has no entry in references.md; not linked")
            return m.group(0)
        href = f"#{rid}" if self.page.stem == "references" else f"references.html#{rid}"
        return self._stash(f'<a class="ref-link" href="{href}">[{rid}]</a>')

    def _sections(self, s: str) -> str:
        out: list[str] = []
        last = 0
        prev_end: int | None = None
        prev_doc: str | None = None
        for m in _SEC.finditer(s):
            pre = s[: m.start()]
            doc: str | None
            dm = _DOC_BEFORE.search(pre)
            lm = _LINK_BEFORE.search(pre)
            if dm and dm.group(1) in DOC_NAMES:
                doc = dm.group(1)
            elif lm and int(lm.group(1)) in self.link_doc:
                doc = self.link_doc[int(lm.group(1))]
            elif prev_end is not None and _CONT.fullmatch(s[prev_end : m.start()]):
                doc = prev_doc
            elif dm:
                doc = None  # PLAN §…, CRIT §…, a standard's clause: not a document here
            elif _LOCAL_BEFORE.search(pre):
                doc = self.page.stem
            else:
                doc = None
            prev_end, prev_doc = m.end(), doc
            href = self._section_href(doc, m.group(1))
            if href:
                begin = m.start()
                if dm and doc == dm.group(1) and dm.start() >= last:
                    begin = dm.start()  # "PHYSICS §16" links as one phrase
                out.append(s[last:begin])
                out.append(self._stash(f'<a class="sec-link" href="{href}">{s[begin : m.end()]}</a>'))
                last = m.end()
        out.append(s[last:])
        return "".join(out)

    def _section_href(self, doc: str | None, label: str) -> str | None:
        if doc is None:
            return None
        tp = self.site.pages.get(doc)
        if tp is None or label not in tp.sections:
            return None
        hid = tp.sections[label]
        return f"#{hid}" if doc == self.page.stem else f"{tp.href}#{hid}"


